"""Generate the cross-language pixel descriptor golden used by parity tests."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pipeline import graphics  # noqa: E402
TARGET = ROOT / "ui" / "test" / "geometry.golden.ts"


def _golden(width: int, height: int) -> str:
    golden = {
        item.id: graphics.graphic_geometry(
            item.id, item.defaults, width, height, {"x": 0.5, "y": 0.5}, 1,
        )
        for item in graphics.DEFINITIONS
    }
    return json.dumps(golden, indent=2, sort_keys=True)


def render() -> str:
    return (
        "/* This file is generated by scripts/export_graphics_geometry.py. */\n"
        f"export const GRAPHIC_GEOMETRY_GOLDEN = {_golden(1920, 1080)} as const;\n"
        "/* The 4K export's canvas: the 1080 design, scaled up. */\n"
        f"export const GRAPHIC_GEOMETRY_GOLDEN_4K = {_golden(3840, 2160)} as const;\n"
    )


def main() -> None:
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
